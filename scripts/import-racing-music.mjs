// Preserve the supplied MP3 bytes and embed them for standalone/blob gameplay.
// Import once: node scripts/import-racing-music.mjs --source /path/to/dist/assets
// Rebuild data from local originals: node scripts/import-racing-music.mjs
// Verify without writing: node scripts/import-racing-music.mjs --check
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const directory=path.join(root,'assets/racing/music');
const tracks=[
  {id:'theme',title:'JCW Theme',file:'jcw-theme.mp3',bytes:4142925,sha256:'5c4f72683117fa4f2ea2609191ecfaca479a94ac20bb08a92c308deaa57afe29',durationSeconds:207.12},
  {id:'fight-club',title:'Fight Club',file:'fight-club.mp3',bytes:2033277,sha256:'523287a3666d4c532a9dcb0df112db01b5167c07b202a1acae7ab5197f9e6e4c',durationSeconds:207.12}
];
const args=process.argv.slice(2),check=args.includes('--check');
let source=null;
for(let i=0;i<args.length;i++){
  if(args[i]==='--check')continue;
  if(args[i]==='--source'&&args[i+1]){source=path.resolve(args[++i]);continue;}
  throw new Error('Usage: import-racing-music.mjs [--check] [--source /path/to/dist/assets]');
}
if(check&&source)throw new Error('--check never copies source files; omit --source.');
if(!check)await fs.mkdir(directory,{recursive:true});
const embedded={};
for(const track of tracks){
  const location=path.join(source||directory,track.file),buffer=await fs.readFile(location);
  const hash=crypto.createHash('sha256').update(buffer).digest('hex');
  if(buffer.length!==track.bytes||hash!==track.sha256)throw new Error(`${track.file} differs from the supplied Lunacy Unlocked original.`);
  if(source)await fs.copyFile(location,path.join(directory,track.file));
  embedded[track.id]={id:track.id,title:track.title,mime:'audio/mpeg',bytes:track.bytes,sha256:hash,src:'data:audio/mpeg;base64,'+buffer.toString('base64')};
}
const manifest={version:1,sourceProject:'Lunacy Unlocked',sourceBuild:'2026-09-13/co/work/lunacy-unlocked/dist',sourceAudioController:'dist/src/audio.js',
  provenance:'Exact supplied MP3 originals reused at the project owner’s request. No audio editing, transcoding or new ownership claim.',
  playback:{loop:true,volume:.22,defaultTrack:'theme',lazy:true},
  tracks:tracks.map(track=>({...track,sourcePath:'dist/assets/'+track.file,assetPath:'assets/racing/music/'+track.file}))};
const outputs=[
  [path.join(directory,'manifest.json'),JSON.stringify(manifest,null,2)+'\n'],
  [path.join(root,'games/racing-music-data.js'),'// Generated by scripts/import-racing-music.mjs; exact supplied MP3 bytes.\nconst RACING_MUSIC_DATA = Object.freeze('+JSON.stringify(embedded)+');\n']
];
for(const [file,content] of outputs){
  if(check){if(await fs.readFile(file,'utf8')!==content)throw new Error(path.relative(root,file)+' is stale; run the importer.');}
  else await fs.writeFile(file,content);
}
console.log(`Racing music ${check?'verified':'embedded'}: ${tracks.length} original MP3s, ${tracks.reduce((n,t)=>n+t.bytes,0)} bytes; no external audio requests.`);
